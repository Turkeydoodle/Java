package Java;

public class Dog {
    private int age;
    private String name;
    private String breed;

    public Dog(int dogage, String dogname, String dogbreed) {
        age = dogage;
        name = dogname;
        breed = dogbreed;
    }

    public int getage() {
        return age;
    }

    public String getname() {
        return name;
    }

    public String breed() {
        return breed;
    }
}
